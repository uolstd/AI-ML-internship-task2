def find_image(img_id, folder):
    """Find image file for a given ID"""
    if pd.isna(img_id):
        return None
    for ext in ['.jpg', '.jpeg', '.png']:
        path = os.path.join(folder, f"{int(img_id)}{ext}")
        if os.path.exists(path):
            return path
    return None

# Add image paths to dataframe
