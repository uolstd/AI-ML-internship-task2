# 5. CREATE PYTORCH DATASET
# ============================================

class HouseDataset(Dataset):
    def __init__(self, X, y, image_paths=None, transform=None):
        self.X = torch.tensor(X, dtype=torch.float32)
        self.y = torch.tensor(y, dtype=torch.float32)
        self.image_paths = image_paths
        self.transform = transform

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        # Get tabular data
        tabular = self.X[idx]

        # Get image (or blank if no image)
        #if self.image_paths is not None and self.image_paths[idx]:
        if self.image_paths is not None and self.image_paths[idx] is not None:
            try:
                img = Image.open(self.image_paths[idx]).convert('RGB')
                if self.transform:
                    img = self.transform(img)
            except:
                img = torch.zeros(3, 224, 224)
        else:
            img = torch.zeros(3, 224, 224)

        return tabular, img, self.y[idx]

# Image preprocessing
transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
])

# Create datasets
train_dataset = HouseDataset(X_train, y_train, paths_train, transform)
val_dataset = HouseDataset(X_val, y_val, paths_val, transform)
test_dataset = HouseDataset(X_test, y_test, paths_test, transform)

# Create data loaders
batch_size = 4 if has_images and len(X_train) >= 4 else 1
train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False)
test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False)

print(f"\nData loaders created with batch size: {batch_size}")

