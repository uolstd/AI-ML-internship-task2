# 6. BUILD MODEL
# ============================================

class PricePredictor(nn.Module):
    def __init__(self, use_images=True):
        super(PricePredictor, self).__init__()

        self.use_images = use_images

        # Image branch (CNN)
        if use_images:
            cnn = models.resnet18(pretrained=True)
            self.cnn = nn.Sequential(*list(cnn.children())[:-1])  # Remove last layer
            # Freeze early layers
            for param in list(self.cnn.parameters())[:-4]:
                param.requires_grad = False

            # Tabular branch
            self.tabular_net = nn.Sequential(
                nn.Linear(4, 32), nn.ReLU(), nn.Dropout(0.2),
                nn.Linear(32, 16), nn.ReLU()
            )
            combined_size = 512 + 16
        else:
            combined_size = 4

        # Combined network
        self.predictor = nn.Sequential(
            nn.Linear(combined_size, 128), nn.ReLU(), nn.Dropout(0.3),
            nn.Linear(128, 64), nn.ReLU(), nn.Dropout(0.2),
            nn.Linear(64, 32), nn.ReLU(),
            nn.Linear(32, 1)
        )

    def forward(self, tabular, image):
        if self.use_images:
            # Get image features
            img_features = self.cnn(image)
            img_features = img_features.view(img_features.size(0), -1)

            # Get tabular features
            tab_features = self.tabular_net(tabular)

            # Combine
            combined = torch.cat([img_features, tab_features], dim=1)
        else:
            combined = tabular

        # Predict price
        return self.predictor(combined).squeeze()

# ============================================
# 7. TRAIN MODEL
# ============================================

device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
model = PricePredictor(use_images=has_images).to(device)
criterion = nn.MSELoss()
optimizer = torch.optim.Adam(model.parameters(), lr=0.001)

print(f"\n{'='*50}")
