# Training loop
print(f"\nTraining started...")
print(f"{'='*50}")

for epoch in range(30):
    # Training phase
    model.train()
    train_loss = 0
    for tabular, img, price in train_loader:
        tabular, img, price = tabular.to(device), img.to(device), price.to(device)

        optimizer.zero_grad()
        pred = model(tabular, img)
        loss = criterion(pred, price)
        loss.backward()
        optimizer.step()

        train_loss += loss.item()

    # Validation phase
    model.eval()
    val_loss = 0
    with torch.no_grad():
        for tabular, img, price in val_loader:
            tabular, img, price = tabular.to(device), img.to(device), price.to(device)
            pred = model(tabular, img)
            val_loss += criterion(pred, price).item()

    # Print progress every 5 epochs
    if (epoch + 1) % 5 == 0:
        avg_train_loss = train_loss / len(train_loader)
        avg_val_loss = val_loss / len(val_loader)
        print(f"Epoch {epoch+1:2d}/30 - Train Loss: {avg_train_loss:.4f}, Val Loss: {avg_val_loss:.4f}")

print("Training complete!")

